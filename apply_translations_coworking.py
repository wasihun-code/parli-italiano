def update_file(file_path, translations_dict):
    with open(file_path, 'r') as f:
        data = json.load(f)

    updated = 0
    for item in data:
        if not item.get('english') or item['english'] == "":
            it = item['italian']
            if it in translations_dict:
                item['english'] = translations_dict[it]
                updated += 1
            else:
                print(f"Missing translation for: {it} in {file_path}")

    with open(file_path, 'w') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    
    print(f"Updated {updated} items in {file_path}")

update_file(file_path_vocab, translations_vocab)
update_file(file_path_phrases, translations_phrases)

