file_path = "src/data/exports/travel/metro_directions/travel_metro_directions_vocabulary.json"
with open(file_path, "r", encoding="utf-8") as f:
    data = json.load(f)

for item in data:
    if not item.get("english") or item["english"] == "":
        it = item["italian"].lower()
        if it in mapping:
            item["english"] = mapping[it]
        else:
            print(f"Missing translation for: {it}")

with open(file_path, "w", encoding="utf-8") as f:
    json.dump(data, f, indent=2, ensure_ascii=False)
