def update_file(file_path, translations):
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    updated = False
    for item in data:
        item_id = item['id']
        if item_id in translations and (not item.get('english') or item['english'] == ""):
            item['english'] = translations[item_id]
            updated = True
            
    if updated:
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
        print(f"Updated {file_path}")
    else:
        print(f"No updates needed for {file_path}")

update_file(vocab_file, vocab_translations)
update_file(phrases_file, phrases_translations)
