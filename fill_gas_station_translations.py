def process_file(file_name, translator):
    path = os.path.join(scenario_path, file_name)
    if not os.path.exists(path):
        print(f"Skipping {file_name}, not found.")
        return
    
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    for item in data:
        # Fill missing English
        if not item.get("english"):
            item["english"] = translator(item["italian"])
            
        # Fill choicesEnglish
        if "choicesItalian" in item:
            choices_it = item["choicesItalian"]
            choices_eng = []
            for cit in choices_it:
                trans = translator(cit)
                if not trans:
                    # Fallback for choices that might not be in our specific map
                    # Use the word translator for vocab choices
                    if translator == translate_word:
                        trans = translate_word(cit)
                    else:
                        trans = cit # fallback to original if still nothing
                choices_eng.append(trans)
            item["choicesEnglish"] = choices_eng
            
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"Processed {file_name}")

process_file(f"{prefix}_vocabulary.json", translate_word)
process_file(f"{prefix}_phrases.json", translate_phrase)
process_file(f"{prefix}_sentences.json", translate_sentence)

print("Done filling translations.")
