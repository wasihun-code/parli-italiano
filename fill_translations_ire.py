import json
import os

def fill_translations(file_path, translations):
    if not os.path.exists(file_path):
        return
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    updated = False
    for item in data:
        if 'english' in item and (not item['english'] or item['english'] == ""):
            it = item['italian'].lower().strip('?!.,')
            if it in translations:
                item['english'] = translations[it]
                updated = True
            else:
                # Fallback for some common patterns or just leave for manual if too many
                pass
                
    if updated:
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

