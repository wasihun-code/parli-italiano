import json
import os

def fill_translations(file_path, translations):
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    count = 0
    for item in data:
        if item['italian'] in translations:
            item['english'] = translations[item['italian']]
            count += 1
        elif not item['english']:
            print(f"Warning: No translation for {item['italian']}")
            
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Updated {count} entries in {file_path}")

