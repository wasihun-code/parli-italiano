def apply_translations(file_name, translations):
    path = os.path.join(scenario_path, file_name)
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    count = 0
    for item in data:
        it = item["italian"]
        if it in translations and not item.get("english"):
            item["english"] = translations[it]
            count += 1
    
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"Applied {count} translations to {file_name}")

apply_translations("shopping_bookstore_vocabulary.json", vocab_translations)
apply_translations("shopping_bookstore_phrases.json", phrase_translations)
