    # Helper function to update JSON
    def update_json(path, mapping, type_label):
        if not os.path.exists(path):
            print(f"File not found: {path}")
            return
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        count = 0
        for item in data:
            it = item.get("italian")
            if it in mapping:
                item["english"] = mapping[it]
                count += 1
            elif not item.get("english"):
                print(f"Warning: No translation for {type_label} '{it}'")
        
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
        print(f"Updated {count} translations in {path}")

    update_json(vocab_path, vocab_map, "Vocabulary")
    update_json(phrases_path, phrases_map, "Phrase")
    update_json(sentences_path, sentences_map, "Sentence")

