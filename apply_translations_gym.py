def translate_file(file_path, translations):
    if not os.path.exists(file_path):
        print(f"File not found: {file_path}")
        return
    
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    for item in data:
        it = item['italian']
        # For phrases, we might want exact matches. For vocabulary, case-insensitive.
        it_key = it.lower().strip('?!.,')
        if it in translations:
            item['english'] = translations[it]
        elif it_key in translations:
            item['english'] = translations[it_key]
        else:
            # Try to handle some common variations if needed
            pass
            
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

