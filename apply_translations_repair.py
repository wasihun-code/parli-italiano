import json
import os

def fill_translations(file_path, translations):
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    changed = False
    for item in data:
        if item.get('english') == "":
            italian = item.get('italian').lower()
            if italian in translations:
                item['english'] = translations[italian]
                changed = True
            else:
                print(f"Missing translation for: {italian} in {file_path}")
    
    if changed:
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
        print(f"Updated {file_path}")

