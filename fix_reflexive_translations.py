base_path = "src/data/exports/reflexive/verbs_verbi_riflessivi/"

# Vocabulary
vocab_file = os.path.join(base_path, "reflexive_verbs_verbi_riflessivi_vocabulary.json")
with open(vocab_file, "r") as f:
    vocab = json.load(f)
for item in vocab:
    if not item.get("english"):
        item["english"] = word_translations.get(item["italian"].lower(), item["italian"] + " [MISSING]")
with open(vocab_file, "w") as f:
    json.dump(vocab, f, indent=2)

# Phrases
phrases_file = os.path.join(base_path, "reflexive_verbs_verbi_riflessivi_phrases.json")
with open(phrases_file, "r") as f:
    phrases = json.load(f)
# Phrases extracted from conversations have "english" field usually
# If missing, I'll need to map them.
with open(phrases_file, "w") as f:
    json.dump(phrases, f, indent=2)

# Sentences
sentences_file = os.path.join(base_path, "reflexive_verbs_verbi_riflessivi_sentences.json")
